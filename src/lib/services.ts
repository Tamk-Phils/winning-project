export function getStoredServiceProviders(): ServiceProvider[] {
  try {
    const raw = localStorage.getItem(PROVIDERS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {
    // fallback
  }
  localStorage.setItem(PROVIDERS_STORAGE_KEY, JSON.stringify(INITIAL_SERVICE_PROVIDERS));
  return INITIAL_SERVICE_PROVIDERS;
}

export function saveServiceProvider(provider: ServiceProvider): ServiceProvider[] {
  const current = getStoredServiceProviders();
  const existingIndex = current.findIndex(p => p.id === provider.id);
  let updated: ServiceProvider[];
  if (existingIndex >= 0) {
    updated = [...current];
    updated[existingIndex] = provider;
  } else {
    updated = [provider, ...current];
  }
  localStorage.setItem(PROVIDERS_STORAGE_KEY, JSON.stringify(updated));
  return updated;
}

export function getStoredServiceBookings(): ServiceBooking[] {
  try {
    const raw = localStorage.getItem(BOOKINGS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {
    // fallback
  }
  localStorage.setItem(BOOKINGS_STORAGE_KEY, JSON.stringify(INITIAL_SERVICE_BOOKINGS));
  return INITIAL_SERVICE_BOOKINGS;
}

export function saveServiceBooking(booking: ServiceBooking): ServiceBooking[] {
  const current = getStoredServiceBookings();
  const updated = [booking, ...current];
  localStorage.setItem(BOOKINGS_STORAGE_KEY, JSON.stringify(updated));
  return updated;
}

export function updateServiceBookingStatus(bookingId: string, status: ServiceBookingStatus): ServiceBooking[] {
  const current = getStoredServiceBookings();
  const updated = current.map(b => b.id === bookingId ? { ...b, status } : b);
  localStorage.setItem(BOOKINGS_STORAGE_KEY, JSON.stringify(updated));
  return updated;
}
